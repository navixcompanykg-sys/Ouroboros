type Planet struct {
	Index int     `json:"i"`
	Type  string  `json:"type"`
	Orbit float64 `json:"orbit"` // клетей от центра звезды
	// Angle/AngVel — положение на орбите как чистая функция игрового времени:
	//   angle(t) = Angle + AngVel × t   (t — игровые месяцы, см. planetPos)
	// Тот же приём, что и у объектов сектора (x = x0 + arc·(t−t0), galaxy.go):
	// сервер ничего не пересчитывает покадрово, клиент рисует любой момент сам.
	Angle    float64        `json:"angle"`  // радианы, начальный угол при t=0
	AngVel   float64        `json:"angVel"` // радиан за игровой месяц, см. orbitalAngVel
	Diameter float64        `json:"d"`
	Owner    string         `json:"owner"`
	Water    int            `json:"water"` // гидросфера 0–100, см. waterRange
	Life     bool           `json:"life"`  // живая биосфера ПРЯМО СЕЙЧАС — не то же самое, что «вымершая» ниже
	Res      map[string]int `json:"res"`   // ключ ресурса → концентрация, у.е. 0–10 000 (15 ключей, см. resourceDefs)

	// ── условия среды (см. envRoll ниже) — вынесены отдельно от Res, потому
	// что это не сырьё, а характеристики планеты, и в клиентском админ-
	// инструменте показываются отдельной таблицей (ТЗ_UI.md §3.6.1), чтобы не
	// захламлять основную таблицу ресурсов.
	Temperature int `json:"temp"`      // Кельвины — игровая калибровка направления (форма формулы реальная — см. envRoll), не буквальные астрофизические цифры
	Pressure    int `json:"pressure"`  // плотность атмосферы, усл. ед. 0–100
	Volcanic    int `json:"volcanic"`  // вулканическая активность, усл. ед. 0–100
	Radiation   int `json:"radiation"` // уровень радиации на поверхности, усл. ед. 0–100
	Toxicity    int `json:"toxicity"`  // токсичность среды, усл. ед. 0–100
}

// ── орбитальное движение планет (третий закон Кеплера) ─────────────────────
//
// Раньше Angle разыгрывался один раз и планета стояла намертво. Теперь она
// обращается вокруг звезды, а период берётся из настоящей формулы, а не из
// произвольного числа: T² ∝ a³/M, то есть
//
//	T = keplerK × √(a³ / M)
//
// где a — радиус орбиты (клети от центра звезды), M — масса звезды в
// условных солнечных (galaxy.go starMass). Из физики следуют оба требуемых
// эффекта сразу, без отдельных правил: чем дальше планета, тем медленнее
// (a³), и чем тяжелее светило, тем быстрее его планеты (÷M) — у синего
// гиганта (10–30 M☉) год короче, чем у красного карлика (0,1–0,6 M☉) на той
// же орбите, примерно в √(30/0,1) ≈ 17 раз.
//
// ── калибровка keplerK: от скорости корабля, а не от «как на Земле» ───────
//
// Первая версия калибровалась по земному году (планета жёлтого карлика на
// орбите 12 обходила звезду за 12 игровых месяцев, keplerK = 0,2887). При
// игровом времени 1:1 с календарём (clock.go) это оказалось непригодно:
// планета сдвигалась на ~0,04° за час игры — движение существовало только
// на бумаге. Требование: игрок должен замечать вращение в пределах реального
// дня, и оно должно что-то значить.
//
// Новая привязка — к скорости корабля: САМАЯ БЫСТРАЯ возможная планета летит
// по орбите ровно в 10 раз медленнее корабля. Эталон скорости взят из
// единственной жёсткой привязки «скорость ↔ расстояние» в ТЗ.md §2.7.4:
// «на 200 000 у.е. корабль пролетает 1 экран телефона за 5 секунд» плюс
// «в масштабе корабля 1 клетка системы = 1 экран» — то есть 0,2 клети/сек.
// (Все четыре двигателя имеют один предел скорости и различаются только
// разгоном, поэтому у «самого медленного» корабля тот же потолок.)
// Отсюда потолок для планеты: 0,02 клети/сек.
//
// Тангенциальная скорость планеты v = ω·a = 2π·√(M/a) / keplerK и
// максимальна при самой тяжёлой звезде и самой близкой орбите:
// M = 30 M☉ (верх диапазона синего гиганта, galaxy.go) и a = 3 (первая
// орбита: шаг 4 минус джиттер 1). Приравняв её к 0,02 клети/сек с учётом
// 2 629 746 реальных секунд в игровом месяце, получаем keplerK = 3,7778e-4 —
// вращение быстрее прежнего в 764 раза.
//
// Что это даёт в реальном времени: земной аналог (жёлтый карлик, орбита 12) —
// оборот за 11,5 часа, то есть 31° за часовую сессию и два оборота в сутки;
// самая медленная планета (красный карлик, внешняя орбита 35) — 4 суток;
// самая быстрая (синий гигант, орбита 3) — 18 минут, это и есть граница
// «в 10 раз медленнее корабля».
//
// Направление обращения у всех планет системы одно (против часовой) — как в
// настоящем протопланетном диске, а не вразнобой.
const keplerK = 3.7778e-4

// orbitalPeriodMonths — период обращения планеты, игровые месяцы.
func orbitalPeriodMonths(orbit, starMassSolar float64) float64 {
	if orbit <= 0 || starMassSolar <= 0 {
		return 0
	}
	return keplerK * math.Sqrt(orbit*orbit*orbit/starMassSolar)
}

// orbitalAngVel — угловая скорость планеты, радиан за игровой месяц.
func orbitalAngVel(orbit, starMassSolar float64) float64 {
	T := orbitalPeriodMonths(orbit, starMassSolar)
	if T <= 0 {
		return 0
	}
	return 2 * math.Pi / T
}

// planetPos — локальные координаты планеты в системе на игровое время months.
// Единственный источник истины о положении планеты: им пользуются и навигация
// корабля (ship.go), и клиент — чтобы «долететь до планеты» и «нарисовать
// планету» не разъезжались.
func planetPos(p Planet, months float64) (x, y float64) {
	a := p.Angle + p.AngVel*months
	return p.Orbit * math.Cos(a), p.Orbit * math.Sin(a)
}

// dockRadiusFactor — радиус причаливания в долях РАДИУСА планеты: корабль
// встаёт на 2/3 радиуса от её центра, то есть ВНУТРИ диска планеты, а не за
// его краем. Так корабль виден «на планете», а не рядом с ней: и на карте
// системы (маркер лежит на диске), и в HUD корабля, где планета в этот момент
// занимает почти весь кадр.
const dockRadiusFactor = 2.0 / 3.0

// planetDockPos — где корабль СТОИТ У планеты: на расстоянии
// dockRadiusFactor·радиус от её ЦЕНТРА, под углом angleOffset ОТНОСИТЕЛЬНО
// собственного угла планеты (angleOffset=0 — со стороны звезды). Угол не
// звёздный, а именно относительно планеты — поэтому причал вращается ВМЕСТЕ
// с планетой (наследует её движение, см. ship.go effectivePos), сохраняя ту
// же сторону, с которой корабль когда-то подлетел (ship.go Navigate считает
// angleOffset по фактическому курсу — ближайшая точка пересечения курса с
// окружностью причаливания, а не всегда одна и та же сторона от звезды).
// Единственная точка правды для «стоянки у планеты»: её же вызывают и
// прокладка курса (Navigate), и снимок положения (currentPlanetPos).
func planetDockPos(p Planet, months float64, angleOffset float64) (x, y float64) {
	a := p.Angle + p.AngVel*months
	pcx, pcy := p.Orbit*math.Cos(a), p.Orbit*math.Sin(a)
	dockR := p.Diameter / 2 * dockRadiusFactor
	dockAngle := a + angleOffset
	return pcx + dockR*math.Cos(dockAngle), pcy + dockR*math.Sin(dockAngle)
}

// ── жизнь: пока только заглушка-маркер, теперь ещё и источник для биогенных
// ресурсов ────────────────────────────────────────────────────────────────
// Полноценная подсистема (ACTIVITY, рождение/гибель жизни во времени,
// атмосфера) не спроектирована — открытый вопрос ТЗ.md §2.5. До неё жизнь —
// два независимых булевых броска, оба с шансом только у планет с
// гидросферой (камень, лёд), растущим с водой:
//   - alive   — живая биосфера сейчас (поле Planet.Life, как раньше);
//   - extinct — вымершая: только если НЕ живая, шанс меньше и не выставляется
//     наружу отдельным полем (влияет только на то, какие ресурсы доступны).
//
// biomass/phosphates требуют именно живой биосферы, carbonates/bitumens —
// живой ИЛИ вымершей (осадочные породы переживают саму жизнь) — см.
// bioAliveOnly/bioFossilOk и использование в makePlanet.
var lifeChanceCap = map[string]float64{"rocky": 0.5, "ice": 0.6}
var extinctChanceCap = map[string]float64{"rocky": 0.25, "ice": 0.30}

func rollLife(rng *rand.Rand, pt string, water int) bool {
	chance, ok := lifeChanceCap[pt]
	if !ok {
		return false
	}
	return rng.Float64() < (float64(water)/100)*chance
}

func rollExtinctLife(rng *rand.Rand, pt string, water int) bool {
	chance, ok := extinctChanceCap[pt]
	if !ok {
		return false
	}
	return rng.Float64() < (float64(water)/100)*chance
}

// systemRadiusRange — радиус звёздной области, клети (ТЗ.md §2.7.4: 25–35).
const (
	systemRadiusMin = 25.0
	systemRadiusMax = 35.0
	orbitStep       = 4.0 // шаг орбит, экраны (ТЗ.md §2.8: 4 ± 1)
	orbitJitter     = 1.0
	orbitOccupancy  = 0.82 // доля занятых слотов: часть орбит пустует
)

// ── метеоритная активность и кольца звезды ──────────────────────────────────
//
// Кольца — отдельная от планет сущность (осколочный диск вокруг самой
// звезды, а не вокруг конкретной планеты): большинство звёзд без колец, реже
// одно, реже всего два — по аналогии со старым v1-реестром (`n_rings`), там
// это тоже было редким признаком.
func rollRings(rng *rand.Rand) int {
	x := rng.Float64()
	switch {
	case x < 0.60:
		return 0
	case x < 0.90:
		return 1
	default:
		return 2
	}
}

// rollMeteorActivity — 1–100, требование: зависит от типа звезды, числа
// планет и наличия колец. Не физическая формула, а взвешенная сумма трёх
// факторов + шум:
//   - планеты (гравитационные возмущения на осколки, насыщается на 8 планетах);
//   - тип звезды (бурная и короткоживущая история оставляет больше обломков:
//     нейтронная > синий гигант > белый карлик > жёлтый/красный/стабильный);
//   - кольца — самый сильный вклад: готовый резервуар осколков на орбитах,
//     регулярно попадающих под возмущение.
func rollMeteorActivity(rng *rand.Rand, starType string, numPlanets, rings int) int {
	const base = 10.0
	planetsFactor := math.Min(30, float64(numPlanets)*4)
	starTypeFactor := map[string]float64{
		"red": 5, "yellow": 8, "stable": 8, "white": 12, "blue": 18, "neutron": 25,
	}[starType]
	ringsFactor := map[int]float64{0: 0, 1: 20, 2: 35}[rings]
	jitter := rng.Float64()*20 - 10 // ±10

	v := base + planetsFactor + starTypeFactor + ringsFactor + jitter
	if v < 1 {
		v = 1
	}
	if v > 100 {
		v = 100
	}
	return int(math.Round(v))
}

// makeStarEnvironment — планеты, кольца, метеоритная активность и радиус
// звёздной области одним вызовом: активность зависит от числа сгенерированных
// планет и от колец той же звезды, поэтому величины разыгрываются вместе.
// sysR наружу нужен клиенту масштаба «Звёздная система» (ТЗ_UI.md §3.7) —
// это и есть размер квадратного поля системы на карте.
// starMassSolar — масса звезды в условных солнечных: нужна планетам для
// периода обращения (orbitalAngVel). Разыгрывается ДО планет и передаётся в
// них, поэтому Object.Mass и период орбит согласованы — это одна и та же
// масса, а не два независимых броска.
func makeStarEnvironment(rng *rand.Rand, starType string, starR, starMassSolar float64) (planets []Planet, rings, meteorActivity int, sysR float64) {
	planets, sysR = generatePlanets(rng, starType, starR, starMassSolar)
	rings = rollRings(rng)
	meteorActivity = rollMeteorActivity(rng, starType, len(planets), rings)
	return planets, rings, meteorActivity, sysR
}

// generatePlanets заселяет звезду планетами.
//
// starR — радиус звезды в окне галактики (нужен для галактического градиента
// и для пояса зоны: планеты у центра галактики богаче металлами и экстримом
// хаоса, у края — беднее и летучими, в стабильной зоне Империи — выработаны).
// starMassSolar — масса светила, задаёт скорость обращения планет (Кеплер).
func generatePlanets(rng *rand.Rand, starType string, starR, starMassSolar float64) ([]Planet, float64) {
	sysR := systemRadiusMin + rng.Float64()*(systemRadiusMax-systemRadiusMin)
	// один бросок «богатства» на всю систему — см. rollStarWealth
	starWealth := rollStarWealth(rng)

	// орбиты: первая на шаге от звезды, дальше с шагом 4 ± 1
	var orbits []float64
	for o := orbitStep + (rng.Float64()*2-1)*orbitJitter; o <= sysR; {
		orbits = append(orbits, o)
		o += orbitStep + (rng.Float64()*2-1)*orbitJitter
	}

	planets := make([]Planet, 0, len(orbits))
	for _, o := range orbits {
		if rng.Float64() > orbitOccupancy {
			continue // орбита пустует
		}
		planets = append(planets, makePlanet(rng, starType, starR, o, sysR, len(planets), starWealth, starMassSolar))
	}
	// система без единой планеты выглядит как ошибка генерации — гарантируем одну
	if len(planets) == 0 && len(orbits) > 0 {
		planets = append(planets, makePlanet(rng, starType, starR, orbits[0], sysR, 0, starWealth, starMassSolar))
	}
	return planets, sysR
}

func makePlanet(rng *rand.Rand, starType string, starR, orbit, sysR float64, idx int, starWealth, starMassSolar float64) Planet {
	pt := planetTypeAt(starType, orbit, sysR)
	dr := planetDiameter[pt]
	wr := waterRange[pt]

	sm, ok := starMod[starType]
	if !ok {
		sm = starMod["yellow"]
	}

	// нормированное положение орбиты внутри системы — для бонуса гелия-3 и
	// для непрерывного градиента orbitMod
	orbitNorm := math.Min(1, orbit/systemRadiusMax)
	orbitFrac := math.Min(1, orbit/sysR)
	zoneMult := zoneScarcity(zoneOfR(starR))

	// гидросфера — раньше воды и жизни, она нужна внутри цикла ресурсов
	// (множитель к водяному льду, вход в оба броска жизни)
	water := int(math.Round(wr[0] + rng.Float64()*(wr[1]-wr[0])))
	hydro := float64(water) / 100

	// жизнь — один раз до цикла ресурсов: alive гейтит biomass/phosphates,
	// alive||extinct гейтит carbonates/bitumens (см. комментарий у rollLife)
	alive := rollLife(rng, pt, water)
	extinct := !alive && rollExtinctLife(rng, pt, water)
	hasBiosphereTrace := alive || extinct

	res := make(map[string]int, len(resourceDefs))
	for _, rd := range resourceDefs {
		base := rd.Base[pt]
		if base <= 0 {
			res[rd.Key] = 0
			continue
		}
		if bioAliveOnly[rd.Key] && !alive {
			res[rd.Key] = 0
			continue
		}
		if bioFossilOk[rd.Key] && !hasBiosphereTrace {
			res[rd.Key] = 0
			continue
		}
		v := base * rd.Rarity * sm[rd.Cat] * galMod(rd.Cat, starR) * zoneMult * orbitMod(rd.Cat, orbitFrac) * starWealth
		// логнормальный разброс месторождения — типичная планета близка к
		// низкому среднему, редкая оказывается на порядок богаче (см. Sigma)
		v *= math.Exp(rd.Sigma * rng.NormFloat64())
		// Гелий-3 имплантирован солнечным ветром в реголит безвоздушных тел:
		// на каменистых/лавовых/голом ядре ближе к звезде его заметно больше
		// (archive: bonus при pressure < 20 и внутренних орбитах). Бонус тоже
		// приведён к масштабу редкости ресурса — иначе он перебивал бы всю
		// остальную формулу для настолько редкого ресурса.
		if rd.Key == "helium3" && (pt == "rocky" || pt == "lava" || pt == "core") {
			v += (1 - orbitNorm) * 1500 * rd.Rarity
		}
		// водяной лёд: гидросфера — множитель к запасу (ТЗ_Ресурсы.md §2)
		if rd.Key == "waterIce" {
			v *= hydro
		}
		res[rd.Key] = clampRes(v)
	}

	owner := "none"
	if rng.Float64() >= 0.55 {
		owner = factionKeys[rng.Intn(len(factionKeys))]
	}

	diameter := math.Round((dr[0]+rng.Float64()*(dr[1]-dr[0]))*100) / 100
	temp, pressure, volcanic, radiation, toxicity := envRoll(rng, starType, pt, orbit, diameter, dr, res)

	return Planet{
		Index:       idx,
		Type:        pt,
		Orbit:       math.Round(orbit*10) / 10,
		Angle:       rng.Float64() * 2 * math.Pi,
		AngVel:      orbitalAngVel(orbit, starMassSolar),
		Diameter:    diameter,
		Owner:       owner,
		Water:       water,
		Life:        alive,
		Res:         res,
		Temperature: temp,
		Pressure:    pressure,
		Volcanic:    volcanic,
		Radiation:   radiation,
		Toxicity:    toxicity,
	}
}

// ── условия среды: температура, давление атмосферы, вулканическая
// активность, радиация, токсичность ─────────────────────────────────────────
//
// Считаются ПОСЛЕ ресурсов — вулканизм и радиация напрямую используют уже
// готовые res["volcanicGases"]/res["radioactives"], а не разыгрываются
// заново, чтобы одна и та же планета не могла случайно оказаться одновременно
// «мало вулканических газов» и «высокая вулканическая активность».
//
// Порядок причинности — ровно тот, что был поставлен как требование:
//  1. вулканическая активность ← объём вулканических газов;
//  2. давление атмосферы ← тип планеты + вулканизм (выброс газов) + размер
//     (больше гравитация — атмосфера держится лучше);
//  3. радиация ← обратный квадрат расстояния до звезды (та же форма, что и
//     радиационные зоны, ТЗ.md §2.8), МИНУС экранирование атмосферой, ПЛЮС
//     фон от собственных радиоактивных пород;
//  4. токсичность ← тип планеты + вулканизм (выброс токсичных газов) +
//     радиация + плотность атмосферы;
//  5. температура ← равновесная от звезды и расстояния (та же логика, что и
//     радиация: жарче ближе к звезде) + парниковый эффект атмосферы +
//     вулканический разогрев.
//
// Все пять на шкале 0–100 (кроме температуры — Кельвины), направление
// эффектов физически честное, но абсолютные числа — игровая калибровка, а не
// буквальный расчёт по реальным константам: та же оговорка, что уже сделана
// для радиационных зон в ТЗ.md §2.8 («реальные светимости различаются на
// 4–7 порядков, для игровой карты немасштабируемы»).
//
// НЕ считаем эти параметры входом для rollLife/rollExtinctLife: по условию
// «жизнь в этой вселенной гибче земной» биосфера способна закрепиться и при
// высокой радиации/токсичности/температуре — единственный фильтр рождения
// жизни остаётся прежним (тип планеты + гидросфера), см. rollLife.
func envRoll(rng *rand.Rand, starType, pt string, orbit, diameter float64, dr [2]float64, res map[string]int) (temp, pressure, volcanic, radiation, toxicity int) {
	zTable, ok := radiationZones[starType]
	if !ok {
		zTable = radiationZones["yellow"]
	}
	z0 := zTable[0]

	// 1. вулканизм: напрямую от объёма вулканических газов (0–10000 → 0–100
	// корнем — совпадает по краям: sqrt(10000)=100), с небольшим шумом
	volcanicF := math.Sqrt(float64(res["volcanicGases"])) * (1 + 0.15*(rng.Float64()*2-1))
	volcanicF = clampPct(volcanicF)

	// 2. давление: база по типу + вклад вулканизма (выброс газов из недр) +
	// бонус за размер планеты внутри своего типового диапазона (гравитация)
	basePressure := map[string]float64{"core": 0, "lava": 15, "rocky": 25, "ice": 10, "gas": 90}[pt]
	sizeFrac := 0.0
	if dr[1] > dr[0] {
		sizeFrac = (diameter - dr[0]) / (dr[1] - dr[0])
	}
	pressureF := basePressure + volcanicF*0.3 + sizeFrac*15
	pressureF *= 1 + 0.2*(rng.Float64()*2-1)
	pressureF = clampPct(pressureF)

	// 3. радиация: I(r) = I0 × (z0/orbit)² — та же форма закона обратных
	// квадратов, что и радиационные зоны звезды (ТЗ.md §2.8), но непрерывная,
	// а не по границам колец; экранирование атмосферой снижает её на 0–85%,
	// голые ядра (Pressure=0) её не гасят вовсе; плюс фон от радиоактивных
	// пород самой планеты — не зависит от звезды и атмосферы.
	rawRadiation := 100 * math.Pow(z0/orbit, 2)
	shield := math.Min(0.85, pressureF/100*0.85)
	radioBackground := math.Sqrt(float64(res["radioactives"])) * 0.5
	radiationF := clampPct(rawRadiation*(1-shield) + radioBackground)

	// 4. токсичность: тип планеты (газовые гиганты и лава токсичны по
	// составу атмосферы даже без вулканизма) + вулканические выбросы +
	// радиационное заражение + сама плотность атмосферы (толще — токсичнее,
	// если состав неблагоприятный, как на Венере)
	baseTox := map[string]float64{"core": 5, "lava": 40, "rocky": 10, "ice": 15, "gas": 60}[pt]
	toxicityF := clampPct(baseTox + volcanicF*0.4 + radiationF*0.2 + pressureF*0.1)

	// 5. температура: равновесная T_eq = T_ref[тип звезды] × sqrt(z0/orbit) —
	// та же логика, что и радиация (ближе к звезде — горячее), калибровано
	// через уже принятые границы радиационных зон, а не буквальные R☉/L
	// (тем же способом, каким ТЗ.md §2.8 уже отказалось от прямого переноса
	// реальных светимостей на карту — разброс в 4–7 порядков непригоден для
	// игровой шкалы). Дальше — парниковый эффект от давления атмосферы (до
	// ×2,2 при максимальном давлении, как у Венеры) и прямой разогрев от
	// вулканической активности.
	tRef := map[string]float64{
		"red": 400, "yellow": 700, "stable": 700, "blue": 2200, "white": 850, "neutron": 1500,
	}[starType]
	if tRef == 0 {
		tRef = 700
	}
	tEq := tRef * math.Sqrt(z0/orbit)
	greenhouse := 1 + math.Min(2.0, pressureF/50)*0.6
	temperatureF := tEq*greenhouse + volcanicF*1.5

	return int(math.Round(temperatureF)), int(math.Round(pressureF)), int(math.Round(volcanicF)),
		int(math.Round(radiationF)), int(math.Round(toxicityF))
}

func clampPct(v float64) float64 {
	if v < 0 {
		return 0
	}
	if v > 100 {
		return 100
	}
	return v
}

// ── потолок шкалы: мягкое поджатие вместо обрубания ─────────────────────────
//
// В v1 стояло жёсткое `clamp(value, 0, 10000)`. На наших множителях это
// схлопывает как раз самые ценные планеты: у голого ядра синего гиганта
// платиноиды считаются как 6800 × 1.55 (звезда) × 1.30 (позиция) = 13 733,
// у нейтронной звезды — 15 062, и всё это одинаково становится 10 000. Замер
// на сиде 12345: у 21 голого ядра из 30 по два-три металла стояли на потолке
// и были неотличимы друг от друга — то есть «лучший источник платиноидов»
// переставал читаться, хотя ради этого система и задумана.
//
// Поджимаем экспоненциально начиная с resKnee: порядок величин сохраняется
// (платиноиды остаются богаче лёгких редких, те — богаче железа), значение
// асимптотически подходит к resHardCap, но никогда его не достигает — в теории.
// На практике при достаточно большом v (несколько одновременных редких
// выбросов v3-формулы — экстремальный starWealth × зона хаоса × 3σ разброс)
// член exp(-(v-resKnee)/head) в float64 округляется РОВНО до 0.0, и капнутое
// значение становится РОВНО resHardCap — по требованию пользователя «ни один
// тип ресурса не мог по формуле достигать максимума в 10000» этого не должно
// происходить именно со значением 10000, поэтому resHardCap задан заметно
// ниже него (9800), а не равен 10000: даже если экспонента схлопнется в ноль,
// результат — 9800, а не потолок шкалы.
const (
	resKnee    = 8000.0
	resHardCap = 9800.0
)

func clampRes(v float64) int {
	if v < 0 {
		return 0
	}
	if v > resKnee {
		head := resHardCap - resKnee
		v = resKnee + head*(1-math.Exp(-(v-resKnee)/head))
	}
	if v > resHardCap {
		v = resHardCap
	}
	return int(math.Round(v))
}
