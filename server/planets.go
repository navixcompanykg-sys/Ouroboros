// ════════════════════════════════════════════════════════════════════════════
// ПЛАНЕТЫ И РАСПРОСТРАНЕНИЕ РЕСУРСОВ
//
// Правила и числа взяты из archive/docs/RESOURCES_design.md (ТЗ.md §2.5 —
// «типы планет и ресурсы пока без изменений относительно v1»). Изменены только
// две вещи, и обе — по требованию нового ТЗ:
//
//  1. Расстановка орбит. В v1 было 36 фиксированных слотов на систему и тип
//     планеты назначался по номеру слота (лава 0–8, камень 9–17, лёд 18–26,
//     газ 27–35). ТЗ.md §2.8 задаёт новую схему: шаг 4 экрана ± 1 при радиусе
//     системы 25–35, то есть 5–8 орбит, а не 36. Прямой перенос невозможен.
//
//  2. Тип планеты определяется не номером орбиты, а тем, в какую
//     РАДИАЦИОННУЮ ЗОНУ звезды эта орбита попала (таблица зон — ТЗ.md §2.8).
//     Порядок тот же, что в v1 (жар → холод: ядро, лава, камень, лёд, газ),
//     но теперь он согласован с типом звезды: у синего гиганта зоны шире, и
//     каменные планеты уезжают дальше от светила, у красного карлика — ближе.
//     Побочный выигрыш: не нужно отдельное правило для Bare Core, оно само
//     получается там, где звезда сожгла кору — внутри зоны сильной радиации.
//
// ── формула запаса ресурса (v3, переработана по запросу пользователя) ──────
//
// Раньше запас = табличная база по типу планеты × множитель звезды ×
// множитель галактической позиции × равномерный разброс ±8%. На практике это
// давало слабо различимые планеты: у всех ресурсов множители одного порядка,
// а равномерный ±8% почти не даёт выбросов ни в бедную, ни в богатую сторону.
//
// Теперь пять независимых входов вместо трёх, и разброс — логнормальный
// (стандартная модель природных месторождений: типичное значение низкое,
// редкий длинный хвост богатых выбросов) вместо равномерного:
//
//   value = база[тип] × Rarity[ресурс]                      — редкость ресурса
//         × множитель_звезды[категория]                     — тип звезды
//         × множитель_позиции(категория, r)                 — радиальный градиент галактики
//         × zoneScarcity(зона)                               — пояс зоны (хаос/колонизация/империя/фронтир)
//         × orbitMod(категория, orbitFrac)                   — удалённость от звезды внутри системы
//         × starWealth                                       — «богатство» звёздной системы (один бросок на звезду)
//         × exp(Sigma[ресурс] × N(0,1))                       — логнормальный разброс месторождения
//
// Result → мягкий потолок clampRes (см. там), с явным запасом ниже 10 000.
// ════════════════════════════════════════════════════════════════════════════

