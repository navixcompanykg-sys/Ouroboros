// ── множитель галактической позиции ─────────────────────────────────────────
// Градиент металличности: ближе к центру галактики — больше тяжёлых элементов
// (много поколений сверхновых), на периферии — больше лёгких летучих.
//
// В архиве вход — birth_radius 0–10. В v2 радиальная ось окна r = 0…120, где
// r=0 — край, ближний к центру галактики (ТЗ.md §2.1). Пересчёт линейный:
// galPos = r / 12, то есть r=0 → 0 (центр), r=120 → 10 (периферия).
func galPos(r float64) float64 { return r / 12 }

func galMod(cat string, r float64) float64 {
	galDelta := (5 - galPos(r)) / 5 // +1 у центра, −1 у края
	switch cat {
	case catMetals, catNuclear:
		return 1 + galDelta*0.35
	case catFuel:
		return 1 - galDelta*0.20
	case catGas:
		return 1 - galDelta*0.15
	default: // catBase
		return 1 + galDelta*0.12
	}
}

// ── пояс зоны: сколько вообще ресурсов осталось ─────────────────────────────
//
// Поверх плавного галактического градиента galMod — дискретная поправка по
// поясам зон (ТЗ.md §2.2), лор и баланс, а не физика:
//   - хаос (1–2)              — экстремальные системы, сверхновых много, богаче всех;
//   - колонизация/нейтраль (3–5) — база, ни бедно ни богато;
//   - стабильная зона Империи (6–8) — САМЫЙ бедный пояс: планеты выработаны
//     давней цивилизацией (по требованию пользователя — «в безопасной зоне
//     ресурсов должно быть меньше всего»);
//   - край галактики (9–12)    — беднее базы просто по позиции, но не выработан
//     (в отличие от Империи там почти нет постоянного населения).
func zoneOfR(r float64) int {
	z := int(r/10) + 1
	if z < 1 {
		return 1
	}
	if z > 12 {
		return 12
	}
	return z
}

func zoneScarcity(zone int) float64 {
	switch {
	case zone <= 2:
		return 1.35
	case zone <= 5:
		return 1.00
	case zone <= 8:
		return 0.30
	default:
		return 0.55
	}
}

// ── удалённость от звезды внутри системы ────────────────────────────────────
//
// Независимо от дискретного деления на типы планет (planetTypeAt), есть
// непрерывный градиент по химии протопланетного диска: тугоплавкие тяжёлые
// элементы конденсируются ближе к звезде, летучие — дальше. orbitFrac — доля
// радиуса системы, 0 (у звезды) … 1 (у её внешнего края).
func orbitMod(cat string, orbitFrac float64) float64 {
	switch cat {
	case catMetals, catNuclear:
		return 1.15 - 0.30*orbitFrac
	case catFuel, catGas:
		return 0.85 + 0.30*orbitFrac
	default:
		return 1.0
	}
}

// ── богатство звёздной системы ───────────────────────────────────────────────
//
// Один логнормальный коэффициент на всю звезду: разыгрывается один раз в
// generatePlanets и множит ресурсы ВСЕХ её планет — «щедрые» и «нищие»
// звёздные системы целиком, а не отдельные богатые планеты внутри бедной
// системы. Логнормальное распределение — стандартная модель природных
// запасов: плотное большинство ниже медианы, редкий длинный хвост богатых
// выбросов, то есть тот же мат. инструмент, что и запрошенное пользователем
// «распределение, больше похожее на природное».
//
// mu/sigma подобраны так, что ровно 75% систем — «нищие» (коэффициент < 1.0),
// 25% — «богатые» (> 1.0): нищих втрое больше, как и просил пользователь,
// причём сам разброс от нищеты к богатству смещён тем же распределением, без
// отдельной формулы для хвоста.
//
// Вывод mu: для логнормального X=exp(mu+sigma·Z), Z~N(0,1),
//
//	P(X<1) = P(Z < −mu/sigma) = Φ(−mu/sigma) = 0.75  ⇒  −mu/sigma = Φ⁻¹(0.75) ≈ 0.6745.
//
// При sigma=0.5 отсюда mu ≈ −0.337.
const (
	starWealthMu    = -0.337
	starWealthSigma = 0.5
)

func rollStarWealth(rng *rand.Rand) float64 {
	return math.Exp(starWealthMu + starWealthSigma*rng.NormFloat64())
}

