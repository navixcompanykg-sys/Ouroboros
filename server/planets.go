// Ресурс: табличная база по типу планеты (форма распределения) + категория
// множителей + параметры редкости/разброса.
type resourceDef struct {
	Key  string
	Cat  string
	Name string
	// база по типу планеты — форма распределения по типам, условная шкала
	// (сама по себе НЕ финальное значение — см. Rarity ниже).
	Base map[string]float64
	// Rarity — множитель редкости, 0–1. Общий вход, отвечающий за то, что
	// редкие ресурсы в среднем на порядки беднее распространённых. Значения
	// подобраны так, что СРЕДНЯЯ концентрация самого частого ресурса (водород)
	// и самого редкого (гелий-3) на всей сгенерированной галактике отличается
	// примерно в 100 раз, как и просил пользователь (замер на сиде 12345:
	// 3010 против 30, см. комментарий у resourceDefs) — но раздельно для
	// каждого ресурса Rarity калибрует именно СРЕДНЕЕ по галактике, а не
	// формальное отношение самих коэффициентов (у гелия-3 оно 0.05, а не
	// 0.01: часть его формы распределения по типам планет — нулевая, что само
	// по себе утяжеляет итоговую редкость сверх коэффициента). Остальные
	// ресурсы лежат на шкале между ними, а не бинарно «обычный/редкий».
	Rarity float64
	// Sigma — параметр логнормального разброса месторождения: чем ресурс
	// реже, тем более «пятнистые» у него залежи — типичная планета почти
	// пуста, но изредка попадается спектакулярно богатая (см. makePlanet).
	Sigma float64
}

