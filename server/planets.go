	// маленьким океаном (как архивный архетип «ДЖУНГЛИ» ≥35%, §43
	// OUROBOROS_design.md) был математически недостижим ни при каком
	// исходе жизни/климата. Диапазон остаётся ассиметричным (5–60, не
