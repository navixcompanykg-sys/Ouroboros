// уходила за края, а на карте системы при ближайшем зуме (4 экрана) занимала
// от трети до трёх четвертей обзора, наползая на соседей. Пропорции между
// типами сохранены — все значения поделены на 3.
var planetDiameter = map[string][2]float64{
	"core":  {0.50, 0.63},
	"lava":  {0.57, 0.77},
	"rocky": {0.60, 0.83},
	"ice":   {0.63, 0.87},
	"gas":   {0.87, 1.00},
}

// Вода — параметр 0–100, а не запас в у.е. (archive: «Вода ★/♻»). Это
